    '{0xCA761232,0XED42,0x11CE,{0xBA,0xCD,0x0,0xAA,0x0,0x57,0xB2,0x23}}',
    '{ 0xca761232 , 0xed42 , 0x11ce , { 0xba , 0xcd , 0x00 , 0xaa , 0x00 , 0x57 , 0xb2 , 0x23 } }',
    '{0xca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}x',
    '{0xca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x123}}',
    '{0xca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x0000000023}}',
    '{0x1ca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}',
    '{0x000000000ca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}',
    '{0xca761232,0x1ed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}',
    '{0xca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}',
    '{0xca761232,0xed42,0x11ce,0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}',
    '{0xca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2}}',
    '{0x,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}',
    '{0xca761232,0xed42,0x11ce,{0x+ba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0x23}}',
    '{0xca761232,0xed42,0x11ce,{0xba,0xcd,0x00,0xaa,0x00,0x57,0xb2,0xzz}}',
    '0xca7612-0xed-11ce-bacd-00aa0057b223', '+ca76123-ed42-11ce-bacd-00aa0057b223', '+0xca7612-+0x2-+0x1-0xba-0xaa0057b223', '+0xca7612-+0x2-+0x1-+0xb-0xaa0057b223',
    'ca761232-ed42-11ce-bacd-0xaa0057b223', 'ca761232-ed42-11ce-bacd-00aa0057b22+', 'ca761232-ed42-11ce-bacd-00aa0057b22g', 'ca761232-ed42-11ce-bacd-00aa0057b22', 'ca761232-ed42-11ce-bacd-00aa0057b2233',
