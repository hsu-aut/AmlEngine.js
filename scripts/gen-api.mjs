// Generates src/engine/api.ts: re-exports every engine type under its name from docs/type-map.tsv
// (classes, static classes, enums as values; interfaces as types). Loading api.ts also loads every
// engine module, so the registry T is complete.
//   node scripts/gen-api.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync('docs/type-map.tsv', 'utf8').trim().split(/\r?\n/).slice(1).map((l) => l.split('\t'));
const values = [];
const types = [];
const missing = [];
const seen = new Set();
for (const [, , , kind, module, name] of rows) {
  if (seen.has(name)) continue;
  if (!existsSync(module)) {
    missing.push(`${name} (no module ${module})`);
    continue;
  }
  const src = readFileSync(module, 'utf8');
  const exported = new RegExp(`export\\s+(?:declare\\s+)?(?:abstract\\s+)?(?:class|interface|enum|const enum|type|const|function)\\s+${name}\\b`).test(src)
    || new RegExp(`export\\s*\\{[^}]*\\b${name}\\b[^}]*\\}`).test(src);
  if (!exported) {
    missing.push(`${name} (not exported by ${module})`);
    continue;
  }
  seen.add(name);
  const path = './' + module.replace(/^src\/engine\//, '').replace(/\.ts$/, '.js');
  const isType = kind === 'interface' || new RegExp(`export\\s+(?:interface|type)\\s+${name}\\b`).test(src);
  (isType ? types : values).push(`export ${isType ? 'type ' : ''}{ ${name} } from '${path}';`);
}
const out = [
  '// Generated by scripts/gen-api.mjs from docs/type-map.tsv. Do not edit.',
  '// The public engine API: every type of Aml.Engine under its C# name.',
  '',
  "import './index.js';",
  '',
  ...values.sort(),
  '',
  ...types.sort(),
  '',
];
writeFileSync('src/engine/api.ts', out.join('\n'));
console.log(`${values.length} values, ${types.length} types`);
if (missing.length) console.log('skipped:\n  ' + missing.join('\n  '));
