// Generates the public API modules from docs/type-map.tsv: src/engine/api.ts re-exports every type
// of Aml.Engine and Aml.Engine.Resources, src/services/api.ts every type of Aml.Engine.Services,
// each under its export name (classes, static classes, enums as values; interfaces as types).
// Loading src/engine/api.ts also loads every engine module, so the registry T is complete;
// src/services/api.ts loads the engine first.
//   node scripts/gen-api.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync('docs/type-map.tsv', 'utf8').trim().split(/\r?\n/).slice(1).map((l) => l.split('\t'));

function generate(root, header, preamble) {
  const values = [];
  const types = [];
  const missing = [];
  const seen = new Set();
  for (const [, , , kind, module, name] of rows) {
    if (!module.startsWith(root + '/') || seen.has(name)) continue;
    if (!existsSync(module)) {
      missing.push(`${name} (no module ${module})`);
      continue;
    }
    const src = readFileSync(module, 'utf8');
    const exported = new RegExp(`export\\s+(?:declare\\s+)?(?:abstract\\s+)?(?:class|interface|enum|const enum|type|const|function)\\s+${name}\\b`).test(src)
      || new RegExp(`export\\s*\\{[^}]*\\b${name}\\b[^}]*\\}`).test(src);
    if (!exported) {
      missing.push(`${name} (not exported by ${module})`);
      continue;
    }
    seen.add(name);
    const path = './' + module.slice(root.length + 1).replace(/\.ts$/, '.js');
    const isType = kind === 'interface' || new RegExp(`export\\s+(?:interface|type)\\s+${name}\\b`).test(src);
    (isType ? types : values).push(`export ${isType ? 'type ' : ''}{ ${name} } from '${path}';`);
  }
  const out = [
    '// Generated by scripts/gen-api.mjs from docs/type-map.tsv. Do not edit.',
    header,
    '',
    preamble,
    '',
    ...values.sort(),
    '',
    ...types.sort(),
    '',
  ];
  writeFileSync(`${root}/api.ts`, out.join('\n'));
  console.log(`${root}/api.ts: ${values.length} values, ${types.length} types`);
  if (missing.length) console.log('skipped:\n  ' + missing.join('\n  '));
}

generate('src/engine', '// The public engine API: every type of Aml.Engine under its C# name.', "import './index.js';");
generate(
  'src/services',
  '// The public services API: every type of Aml.Engine.Services under its C# name.',
  "import '../engine/index.js';",
);
