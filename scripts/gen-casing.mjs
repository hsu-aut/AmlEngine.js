// Generates src/system/casing-data.ts: the simple case mappings of .NET 8 (char.ToUpperInvariant,
// char.ToLowerInvariant, OrdinalCasing.ToUpper and the same for supplementary code points), taken
// from the gapsinfra oracle output (cases str.upperTable, str.lowerTable, str.oicTable and
// str.suppTable in test/gapsinfra/cases.json). The port uses these fixed tables instead of the
// toUpperCase/toLowerCase of the JavaScript environment, whose Unicode version differs between
// Node and browser versions.
//   node scripts/gen-casing.mjs [cases.json] [oracle-out.json] [out.ts]
import { readFileSync, writeFileSync } from 'node:fs';

const [casesFile = 'test/gapsinfra/cases.json', oracleFile = 'test/oracle-out/gapsinfra.json', out = 'src/system/casing-data.ts'] = process.argv.slice(2);
const cases = JSON.parse(readFileSync(casesFile, 'utf8'));
const results = JSON.parse(readFileSync(oracleFile, 'utf8'));

function table(fn, arg) {
  const i = cases.findIndex((c) => c.fn === fn && (arg === undefined || c.args[0] === arg));
  if (i < 0 || !('ok' in results[i])) throw new Error(`no oracle result for ${fn} ${arg ?? ''}`);
  return results[i].ok
    .split(',')
    .filter(Boolean)
    .map((p) => p.split(':').map((x) => parseInt(x, 16)));
}

/** Runs [start, count, delta, step]: code start + k * step (k < count) maps to itself + delta. */
function runs(pairs) {
  const out = [];
  let i = 0;
  while (i < pairs.length) {
    const [start, to] = pairs[i];
    const delta = to - start;
    let best = { count: 1, step: 1 };
    for (const step of [1, 2]) {
      let count = 1;
      while (i + count < pairs.length && pairs[i + count][0] === start + count * step && pairs[i + count][1] - pairs[i + count][0] === delta) count++;
      if (count > best.count) best = { count, step };
    }
    out.push(start, best.count, delta, best.step);
    i += best.count;
  }
  return out;
}

const tables = {
  UPPER: ['char.ToUpperInvariant (BMP)', table('str.upperTable')],
  LOWER: ['char.ToLowerInvariant (BMP)', table('str.lowerTable')],
  ORDINAL_UPPER: ['OrdinalCasing.ToUpper(char), the upper casing of OrdinalIgnoreCase (BMP)', table('str.oicTable')],
  SUPP_UPPER: ['string.ToUpperInvariant for supplementary code points', table('str.suppTable', 'upper')],
  SUPP_LOWER: ['string.ToLowerInvariant for supplementary code points', table('str.suppTable', 'lower')],
  SUPP_ORDINAL_UPPER: ['CharUnicodeInfo.ToUpper, the upper casing of OrdinalIgnoreCase for supplementary code points', table('str.suppTable', 'oic')],
};

let ts = `// Generated by scripts/gen-casing.mjs from the gapsinfra oracle output: simple case mappings of
// .NET 8 on Windows 11 (ICU of the system for the invariant culture, the Unicode data of .NET for
// OrdinalIgnoreCase). Do not edit.
//
// Each table is a list of runs [start, count, delta, step]: the code points start + k * step
// (0 <= k < count) map to themselves plus delta.
`;
for (const [name, [doc, pairs]] of Object.entries(tables)) {
  const r = runs(pairs);
  ts += `\n/** ${doc}: ${pairs.length} mappings. */\nexport const ${name}: readonly number[] = [\n`;
  for (let i = 0; i < r.length; i += 16) ts += `  ${r.slice(i, i + 16).join(', ')},\n`;
  ts += '];\n';
}
writeFileSync(out, ts);
console.log(Object.entries(tables).map(([n, [, p]]) => `${n} ${p.length}`).join(', '), '->', out);
