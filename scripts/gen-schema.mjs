// Converts the schema tables exported by the oracle (`Oracle schema <dir>`) into compact TS modules:
// identical sub-objects are stored once in a pool and referenced by index.
//   node scripts/gen-schema.mjs test/oracle-out/schema src/schema/data
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [inDir = 'test/oracle-out/schema', outDir = 'src/schema/data'] = process.argv.slice(2);
mkdirSync(outDir, { recursive: true });

for (const name of ['caex30', 'caex215']) {
  const data = JSON.parse(readFileSync(join(inDir, `${name}.json`), 'utf8'));
  const pool = [];
  const index = new Map();
  const intern = (v) => {
    if (v === null || typeof v !== 'object') return v;
    const packed = Array.isArray(v) ? v.map(intern) : Object.fromEntries(Object.entries(v).map(([k, x]) => [k, intern(x)]));
    const key = JSON.stringify(packed);
    let id = index.get(key);
    if (id === undefined) {
      id = pool.length;
      pool.push(packed);
      index.set(key, id);
    }
    return { $: id };
  };
  const infos = data.infos.map((i) => intern(i).$);
  const out = { namespace: data.namespace, keys: data.keys, infos, pool };
  const body = JSON.stringify(out);
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/gen-schema.mjs from the tables Aml.Engine 4.5.2 compiles from its CAEX XSD.\n` +
      `// Do not edit.\n\nimport type { PackedSchema } from '../SchemaModel.js';\n\n` +
      `const data: PackedSchema = ${body};\n\nexport default data;\n`,
  );
  console.log(`${name}: ${body.length} chars, ${pool.length} pooled objects`);
}
