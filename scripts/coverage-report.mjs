// Merges V8 coverage runs (istanbul JSON) and lists functions of src/ never executed by any test.
//   node scripts/coverage-report.mjs <out.md> <coverage-final.json>...
// docs/coverage.md is made from two runs, both with
//   --coverage.enabled --coverage.provider=v8 --coverage.reporter=json --coverage.include='src/**'
//   --testTimeout=600000 --coverage.reportsDirectory=<dir>
// 1. the whole suite, the read package on a sample (READS_OUT=<dir> with 28 of the outputs of
//    test/oracle-out/reads: the generated documents of test/reads and a few corpus files; all of
//    them take about 20 minutes without coverage);
// 2. the engine packages of scripts/services-check.mjs with the services registered
//    (AMLENGINE_SERVICES=lookup,uniquename,undo, ORACLE_OUT=test/oracle-out-services/<list>).
import { readFileSync, writeFileSync } from 'node:fs';
import { relative, sep } from 'node:path';

const [out, ...inputs] = process.argv.slice(2);
const files = new Map();
for (const input of inputs) {
  const data = JSON.parse(readFileSync(input, 'utf8'));
  for (const [path, cov] of Object.entries(data)) {
    const key = relative(process.cwd(), path).split(sep).join('/');
    const cur = files.get(key);
    if (!cur) {
      files.set(key, { fnMap: cov.fnMap, f: { ...cov.f }, s: { ...cov.s }, statementMap: cov.statementMap });
    } else {
      for (const k of Object.keys(cov.f)) cur.f[k] = (cur.f[k] ?? 0) + cov.f[k];
      for (const k of Object.keys(cov.s)) cur.s[k] = (cur.s[k] ?? 0) + cov.s[k];
    }
  }
}
const rows = [];
let fnTotal = 0, fnHit = 0, stTotal = 0, stHit = 0;
const byArea = new Map();
for (const [file, c] of [...files].sort()) {
  const fns = Object.keys(c.fnMap);
  const missed = fns.filter((k) => !c.f[k]).map((k) => `${c.fnMap[k].name}:${c.fnMap[k].loc.start.line}`);
  const st = Object.keys(c.s);
  const stMissed = st.filter((k) => !c.s[k]).length;
  fnTotal += fns.length; fnHit += fns.length - missed.length;
  stTotal += st.length; stHit += st.length - stMissed;
  const area = file.split('/').slice(0, file.startsWith('src/engine') ? 3 : 2).join('/');
  const a = byArea.get(area) ?? { fn: 0, fnHit: 0, st: 0, stHit: 0 };
  a.fn += fns.length; a.fnHit += fns.length - missed.length; a.st += st.length; a.stHit += st.length - stMissed;
  byArea.set(area, a);
  if (missed.length) rows.push({ file, total: fns.length, missed });
}
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) : '100.0');
let md = `# Coverage of the port by the oracle tests\n\nGenerated by scripts/coverage-report.mjs. Functions: ${fnHit}/${fnTotal} (${pct(fnHit, fnTotal)} %), statements: ${stHit}/${stTotal} (${pct(stHit, stTotal)} %).\n\n| Area | Functions | Statements |\n|---|---|---|\n`;
for (const [area, a] of [...byArea].sort()) md += `| ${area} | ${a.fnHit}/${a.fn} (${pct(a.fnHit, a.fn)} %) | ${pct(a.stHit, a.st)} % |\n`;
md += `\n## Functions never executed\n\nWhy each of them is not reached is written in docs/coverage-notes/ (per oracle package and services area).\n\n`;
for (const r of rows) md += `- \`${r.file}\` (${r.missed.length}/${r.total}): ${r.missed.join(', ')}\n`;
writeFileSync(out, md);
console.log(`functions ${fnHit}/${fnTotal} (${pct(fnHit, fnTotal)} %), statements ${pct(stHit, stTotal)} %`);
for (const [area, a] of [...byArea].sort()) console.log(`${area.padEnd(40)} fn ${pct(a.fnHit, a.fn).padStart(5)} %  st ${pct(a.stHit, a.st).padStart(5)} %  (${a.fn - a.fnHit} fn missed)`);
